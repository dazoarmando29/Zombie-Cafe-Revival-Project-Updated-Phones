#!/usr/bin/env python3
"""Generate host stub tables from the original 32-bit engine ELF.

Reads  : src/lib/armeabi/libZombieCafeAndroid.so
Writes : host/generated/engine_tables.h

Emits:
  - kEngineImportNames[] : undefined (imported) symbols the engine needs,
    in symbol-table order, with ENGINESYM_* indices.
  - kEngineJniExports[]   : Java_* entry points + JNI_OnLoad with their RVAs.
  - kEngineBaseInfo      : ELF layout constants for the loader.

Run:  python host/tools/gen_tables.py
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ELF = ROOT / "src" / "lib" / "armeabi" / "libZombieCafeAndroid.so"
OUT = ROOT / "host" / "generated" / "engine_tables.h"


def main() -> int:
    d = ELF.read_bytes()
    assert d[:4] == b"\x7fELF", "not an ELF"
    assert d[4] == 1, "expected ELF32"
    e_phoff, = struct.unpack_from("<I", d, 28)
    e_phentsize, e_phnum = struct.unpack_from("<HH", d, 42)

    loads = []   # (offset, vaddr, filesz, memsz, flags)
    dyn = None
    for i in range(e_phnum):
        o = e_phoff + i * e_phentsize
        t, po, pv, pp, pf, pm, pfl, pa = struct.unpack_from("<IIIIIIII", d, o)
        if t == 1:
            loads.append((po, pv, pf, pm, pfl))
        elif t == 2:
            dyn = (po, pf)

    off, fsz = dyn
    tags = {}
    for i in range(0, fsz, 8):
        t, v = struct.unpack_from("<II", d, off + i)
        tags.setdefault(t, []).append(v)
        if t == 0:
            break

    def v2o(v):
        for po, pv, pf, pm, pfl in loads:
            if pv <= v < pv + pf:
                return po + (v - pv)
        return None

    strtab = v2o(tags[5][0])
    syment = tags.get(11, [16])[0]
    symoff = v2o(tags[6][0])
    if 4 in tags:  # DT_HASH
        nsyms = struct.unpack_from("<II", d, v2o(tags[4][0]))[1]
    else:  # DT_GNU_HASH
        g = v2o(tags[0x6FFFFEF5][0])
        nb, so, bloom, _ = struct.unpack_from("<IIII", d, g)
        bo = g + 16 + bloom * 4
        nsyms = so
        for b in range(nb):
            (v,) = struct.unpack_from("<I", d, bo + b * 4)
            nsyms = max(nsyms, v)
        nsyms = min(nsyms + 8, 8000)

    pltgot = tags.get(3, [0])[0]  # DT_PLTGOT

    imports = []   # (name, elf_sym_index)
    jni = []       # (name, rva, size)
    for i in range(nsyms):
        st_name, st_value, st_size, st_info, st_other, st_shndx = struct.unpack_from(
            "<IIIBBH", d, symoff + i * syment)
        if st_name == 0:
            continue
        end = d.index(b"\0", strtab + st_name)
        name = d[strtab + st_name:end].decode("ascii", "replace")
        bind, typ = st_info >> 4, st_info & 0xF
        if st_shndx == 0 and typ in (1, 2):  # undefined func/object
            imports.append((name.split("@")[0], name, i))
        if bind == 1 and typ == 2 and (name.startswith("Java_") or name == "JNI_OnLoad"):
            jni.append((name, st_value, st_size))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="\n") as f:
        f.write("/* AUTO-GENERATED by host/tools/gen_tables.py - do not edit. */\n")
        f.write("#pragma once\n\n#include <stdint.h>\n\n")

        f.write("/* ---- engine ELF layout ---- */\n")
        f.write("static const uint32_t kEngineLoadCount = %d;\n" % len(loads))
        f.write("typedef struct { uint32_t off, vaddr, filesz, memsz, flags; } EngineLoadSeg;\n")
        f.write("static const EngineLoadSeg kEngineLoads[] = {\n")
        for po, pv, pf, pm, pfl in loads:
            f.write("  {0x%x, 0x%x, 0x%x, 0x%x, 0x%x},\n" % (po, pv, pf, pm, pfl))
        f.write("};\n")
        f.write("static const uint32_t kEnginePltGot = 0x%x;\n\n" % pltgot)

        f.write("/* ---- imported symbols (undefined in engine) ---- */\n")
        f.write("#define ENGINE_IMPORT_COUNT %d\n" % len(imports))
        f.write("static const char *const kEngineImportNames[ENGINE_IMPORT_COUNT] = {\n")
        for norm, _orig, _i in imports:
            esc = norm.replace("\\", "\\\\").replace('"', '\\"')
            f.write('  "%s",\n' % esc)
        f.write("};\n")
        # map elf sym index -> import slot
        f.write("typedef struct { uint32_t sym_index, import_slot; } EngineImportMap;\n")
        f.write("static const EngineImportMap kEngineImportBySym[] = {\n")
        for slot, (_n, _o, i) in enumerate(imports):
            f.write("  {%d, %d},\n" % (i, slot))
        f.write("};\n\n")

        f.write("/* ---- JNI entry points exported by engine ---- */\n")
        f.write("#define ENGINE_JNI_COUNT %d\n" % len(jni))
        f.write("typedef struct { const char *name; uint32_t rva; uint32_t size; } EngineJniExport;\n")
        f.write("static const EngineJniExport kEngineJniExports[] = {\n")
        for name, rva, size in jni:
            f.write('  {"%s", 0x%x, %d},\n' % (name, rva, size))
        f.write("};\n")

    print("imports: %d  jni: %d  loads: %d -> %s" % (len(imports), len(jni), len(loads), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
